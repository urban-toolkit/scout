def _save_chart_manifest(manifest: dict) -> None:
    _atomic_write_text(CHART_MANIFEST_PATH, json.dumps(manifest, indent=2))


def _generate_chart_file(render_fn_name: str, code: str, engine: str) -> str:
    if engine == "vega-lite":
        # code is already validated as parseable JSON by the caller. Embed it
        # as JSON.parse("<escaped text>") rather than a raw JS object literal -
        # a spec with a top-level key literally named "__proto__" behaves
        # differently as a re-parsed JSON string (an own data property, safe)
        # vs. a JS object literal (sets the object's prototype instead). This
        # makes the generated file byte-for-byte equivalent to what the
        # author's editor held, regardless of key names.
        spec_obj = json.loads(code)
        spec_js_string_literal = json.dumps(json.dumps(spec_obj))
        return (
            "// @ts-nocheck\n"
            "// AUTO-GENERATED by Chart Studio (Vega-Lite). Edits here are overwritten on republish.\n"
            "import type { ChartRenderFn } from \"../renderers/genericChartRenderer\";\n"
            "import { renderVegaLiteSpec } from \"../renderers/vegaLiteRuntime\";\n\n"
            f"const SPEC = JSON.parse({spec_js_string_literal});\n\n"
            f"export const {render_fn_name}: ChartRenderFn = (container, data, params, d3, containerWidth) => {{\n"
            "  return renderVegaLiteSpec(container, SPEC, data, containerWidth);\n"
            "};\n"
        )

    indented_code = textwrap.indent(code.rstrip(), "  ")
    return (
        # @ts-nocheck: pasted D3/JS is arbitrary author code, not written
        # against this project's strict tsconfig (noImplicitAny on untyped
        # D3 callback params, noUnusedParameters when a chart doesn't need
        # every one of container/data/params/d3, etc.) - a genuine syntax
        # error still fails to parse and is not suppressed by this. The
        # ChartRenderFn annotation below is inert under @ts-nocheck (nothing
        # is actually checked against it) - it's kept anyway so every
        # generated chart file reads the same way, regardless of name.
        "// @ts-nocheck\n"
        "// AUTO-GENERATED by Chart Studio. Edits here are overwritten on republish.\n"
        "import type { ChartRenderFn } from \"../renderers/genericChartRenderer\";\n\n"
        f"export const {render_fn_name}: ChartRenderFn = (container, data, params, d3, containerWidth) => {{\n"
        "  container.innerHTML = \"\";\n"
        f"{indented_code}\n"
        "};\n"
    )


def _regenerate_chart_registry(manifest: dict) -> None:
    imports = [
        f'import {{ {rec["componentName"]} }} from "./{rec["componentFile"][:-3]}";'
        for rec in manifest.values()
    ]
    entries = [f"  {json.dumps(name)}: {rec['componentName']}," for name, rec in manifest.items()]
    content = (
        "// AUTO-GENERATED by Chart Studio publish. Do not edit by hand - regenerated\n"
        "// in full on every publish.\n"
        'import type { ChartRenderFn } from "../renderers/genericChartRenderer";\n'
        + ("\n" + "\n".join(imports) + "\n" if imports else "\n")
        + "\nexport const customChartRenderers: Record<string, ChartRenderFn> = {\n"
        + ("\n".join(entries) + "\n" if entries else "")
        + "};\n"
    )
    _atomic_write_text(FRONTEND_CHARTS_GENERATED_DIR / CHART_REGISTRY_FILENAME, content)


def _check_chart_name_collision(name: str, component_file: str, manifest: dict) -> str | None:
    cf_lower = component_file.lower()
    if cf_lower in {f.lower() for f in RESERVED_CHART_FILES}:
        return f"'{name}' would generate '{component_file}', which collides with an existing built-in file"
    for other_name, rec in manifest.items():
        if other_name == name:
            continue  # republishing the same chart overwrites itself - allowed
        if rec["componentFile"].lower() == cf_lower:
            return f"'{name}' collides with existing chart type '{other_name}' (both generate {component_file})"
    return None

def start_worker():
    global worker_proc, worker_python_exe

    if worker_proc is not None and worker_proc.poll() is None:
        # already running
        return

    project_dir = Path(__file__).parent
    python_exe = Path(sys.executable)

    if not python_exe.exists():
        python_exe = project_dir / "envs" / ("python.exe" if os.name == "nt" else "bin/python")

    if not python_exe.exists():
        raise RuntimeError(f"Python interpreter not found at: {python_exe}")

    worker_python_exe = python_exe

    worker_proc = subprocess.Popen(
        [str(python_exe), "-u", "python_worker.py"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        cwd=str(project_dir),
        env={**os.environ, "PYTHONPATH": str(project_dir) + os.pathsep + os.environ.get("PYTHONPATH", "")},
        bufsize=1,  # line-buffered
    )

    print("[WORKER] Started python_worker process PID:", worker_proc.pid)

def send_code_to_worker(code: str) -> dict:
    """
    Sends code to the persistent worker and returns a dict:
    { "ok": bool, "stdout": str, "stderr": str }
    """
    global worker_proc

    if worker_proc is None or worker_proc.poll() is not None:
        start_worker()

    with worker_lock:
        req = {"code": code}
        line = jsonlib.dumps(req) + "\n"

        assert worker_proc.stdin is not None
        worker_proc.stdin.write(line)
        worker_proc.stdin.flush()

        assert worker_proc.stdout is not None
        resp_line = worker_proc.stdout.readline()
        if not resp_line:
            raise RuntimeError("Worker process terminated unexpectedly")

    resp = jsonlib.loads(resp_line)
    return resp

# Remove cached outputs on exit
def cleanup_served():
    try:
        out_resolved = OUT_DIR.resolve()
        data_resolved = DATA_DIR.resolve()
        if data_resolved in out_resolved.parents and out_resolved.name == "served":
            if OUT_DIR.exists():
                shutil.rmtree(OUT_DIR, ignore_errors=True)
                print(f"[CLEANUP] Removed {OUT_DIR}")
        else:
            print(f"[CLEANUP] Refusing to remove unexpected path: {OUT_DIR}")
    except Exception as e:
        app.logger.error(f"[CLEANUP] Failed: {e}")

def register_cleanup_handlers():
    import atexit
    atexit.register(cleanup_served)

    def _handler(sig, frame):
        cleanup_served()
        sys.exit(0)

    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(sig, _handler)
        except Exception:
            pass

if os.environ.get("WERKZEUG_RUN_MAIN") == "true" or not app.debug:
    register_cleanup_handlers()

