def _as_field_list(value):
    """comparison grammar: x*/y* - a bare string is shorthand for a 1-item set."""
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    return list(value)


@app.post("/api/comparison-view")
def comparison_view():
    data = request.get_json(force=True)

    print("Received comparison view request:", data)
    key = data.get("key", [])
    x_fields = _as_field_list(data.get("x"))
    y_fields = _as_field_list(data.get("y"))
    chart = data.get("chart", "")
    props = data.get("props", {})

    if not key:
        return jsonify({"error": "key must be non-empty"}), 400

    fields = x_fields + y_fields
    if not fields:
        return jsonify({"error": "At least one field must be declared via x or y"}), 400

    axis = "x" if x_fields else "y"
    axis_label = fields[0]

    results = {}  # per scenario key: only the fields declared via x/y
    for k in key:
        csv_path = metric_subdir / f"{k}.csv"
        try:
            df = pd.read_csv(csv_path)
        except FileNotFoundError:
            return jsonify({"error": f"No metric data found for key '{k}'", "key": k}), 404

        row = {}
        for field in fields:
            if field not in df.columns:
                return jsonify({
                    "error": f"Field '{field}' not found for key '{k}'",
                    "key": k,
                    "field": field,
                }), 400
            row[field] = float(df.iloc[0][field])
        results[k] = row

    return jsonify({
        "status": "ok",
        "axis": axis,
        "axisLabel": axis_label,
        "props": props,
        "data": results,
        "chart": chart,
    })


@app.post("/api/seed-metric-data")
def seed_metric_data():
    # Lets Chart Studio's "Push to backend" button write its Sample data
    # (the same shape comparison_view() reads) as real per-scenario CSVs -
    # so a chart can be tested against /api/comparison-view immediately,
    # without running the actual computation pipeline. Overwrites any
    # existing metric/<key>.csv for the keys supplied.
    payload = request.get_json(force=True)
    data = payload.get("data")

    if not isinstance(data, dict) or not data:
        return jsonify({"error": "data must be a non-empty object of key -> {field: number}"}), 400

    for key, row in data.items():
        if not CHART_TYPE_NAME_RE.match(key):
            return jsonify({
                "error": f"'{key}' is not a valid scenario key (letters, numbers, underscores, hyphens only)",
            }), 400
        if not isinstance(row, dict) or not row:
            return jsonify({"error": f"value for '{key}' must be a non-empty object of field -> number"}), 400
        for field, value in row.items():
            if not isinstance(value, (int, float)) or isinstance(value, bool):
                return jsonify({
                    "error": f"'{key}.{field}' must be a number, got {type(value).__name__}",
                }), 400

    written = []
    for key, row in data.items():
        csv_text = pd.DataFrame([row]).to_csv(index=False)
        _atomic_write_text(metric_subdir / f"{key}.csv", csv_text)
        written.append(key)

    return jsonify({"status": "ok", "written": written})


