@app.post("/api/chart-types")
def publish_chart_type():
    data = request.get_json(force=True)
    name = (data.get("name") or "").strip()
    description = data.get("description", "")
    code = data.get("code", "")
    engine = data.get("engine", "d3")

    if not CHART_TYPE_NAME_RE.match(name):
        return jsonify({
            "error": "Chart type name must be non-empty and contain only letters, numbers, underscores, and hyphens",
        }), 400

    if engine not in ("d3", "vega-lite"):
        return jsonify({"error": "engine must be 'd3' or 'vega-lite'"}), 400

    if engine == "vega-lite":
        try:
            json.loads(code)
        except json.JSONDecodeError as e:
            return jsonify({"error": f"Spec must be valid JSON: {e}"}), 400
    elif not code.strip():
        return jsonify({"error": "code must be non-empty"}), 400

    if not FRONTEND_SRC_DIR.exists():
        return jsonify({
            "error": "Publishing requires the dev stack (docker-compose.dev.yml) - frontend "
                     "source is not mounted in this environment.",
        }), 503

    render_fn_name = "render" + _pascal_case(name)
    component_file = "comparison" + _pascal_case(name) + ".generated.ts"

    manifest = _load_chart_manifest()

    collision = _check_chart_name_collision(name, component_file, manifest)
    if collision:
        return jsonify({"error": collision}), 400

    _atomic_write_text(
        FRONTEND_CHARTS_GENERATED_DIR / component_file,
        _generate_chart_file(render_fn_name, code, engine),
    )

    record = {
        "name": name,
        "description": description,
        "code": code,
        "engine": engine,
        "componentFile": component_file,
        "componentName": render_fn_name,
        "createdAt": datetime.now(timezone.utc).isoformat(),
    }
    manifest[name] = record
    _save_chart_manifest(manifest)
    _regenerate_chart_registry(manifest)

    return jsonify({"status": "ok", **record})

@app.post("/api/infer-filetype")
def infer_filetype():
    payload = request.get_json(silent=True) or {}

    ref_keys = ["ref", "ref_base", "ref_comp"]
    ref = None

    for key in ref_keys:
        if key in payload and payload[key]:
            ref = payload[key]
            break

    if not ref:
        return jsonify({"ok": False, "error": "missing ref"}), 400
    
    result = {
        "ok": True,
        "ref": ref,
        "kind": None,       # "vector" | "raster" | None
        "is_dir": None,     # bool | None
        "file_type": None,        # ".geojson" | ".png" | etc | None
        "path": None,       # optional debug
    }

    vector_path = next(vector_subdir.glob(f"{ref}.*"), None)
    if vector_path is not None:
        return jsonify({
            "ok": True,
            "kind": "vector",
            "is_dir": False,
            "file_type": vector_path.suffix.lower(),
        }), 200
    
    # -------------------------
    # 2) Raster (file OR directory)
    # -------------------------

    # Case 1: direct file match (e.g., A.tif)
    raster_file = next(raster_subdir.glob(f"{ref}.*"), None)
    if raster_file is not None and raster_file.is_file():
        return jsonify({
            "ok": True,
            "kind": "raster",
            "is_dir": False,
            "file_type": raster_file.suffix.lower(),
        }), 200


    # Case 2: directory match (e.g., raster/A/)
    raster_path = raster_subdir / ref
    if raster_path.exists() and raster_path.is_dir():
        any_file = next((p for p in raster_path.iterdir() if p.is_file()), None)
        ext = any_file.suffix.lower() if any_file else None

        return jsonify({
            "ok": True,
            "kind": "raster",
            "is_dir": True,
            "file_type": ext,
        }), 200

    # -------------------------
    # 3) Not found
    # -------------------------
    return jsonify({
        "ok": True,
        "kind": None,
        "is_dir": None,
        "file_type": None,
    }), 200


