@app.post("/api/chart-types")
def publish_chart_type():
    data = request.get_json(force=True)
    # Set only when re-publishing a chart Chart Studio already loaded (via
    # "Load existing chart" or "Edit in Chart Studio") - overwrites that
    # exact chart in place, under its existing real identifier, regardless
    # of what displayName now says. Omitted for a brand-new chart, whose
    # real identifier doesn't exist yet and is minted below.
    existing_name = (data.get("name") or "").strip()
    display_name = (data.get("displayName") or "").strip()
    description = data.get("description", "")
    code = data.get("code", "")
    engine = data.get("engine", "d3")
    # The "Example usage"/"Sample data" JSON Chart Studio's Preview uses -
    # persisted so republishing doesn't lose an author's edits to them, and
    # so loading this chart back into Studio (or eventually Chart Gallery)
    # can show the same worked example again instead of a guessed one.
    example_usage = data.get("exampleUsage")
    sample_data = data.get("sampleData")

    if not display_name:
        return jsonify({"error": "Chart name must be non-empty"}), 400

    if engine not in ("d3", "vega-lite"):
        return jsonify({"error": "engine must be 'd3' or 'vega-lite'"}), 400

    if engine == "vega-lite":
        try:
            json.loads(code)
        except json.JSONDecodeError as e:
            return jsonify({"error": f"Spec must be valid JSON: {e}"}), 400
    elif not code.strip():
        return jsonify({"error": "code must be non-empty"}), 400

    if not FRONTEND_SRC_DIR.exists():
        return jsonify({
            "error": "Publishing requires the dev stack (docker-compose.dev.yml) - frontend "
                     "source is not mounted in this environment.",
        }), 503

    manifest = _load_chart_manifest()

    if existing_name:
        if not CHART_TYPE_NAME_RE.match(existing_name) or existing_name not in manifest:
            return jsonify({"error": f"No existing chart type named '{existing_name}'"}), 404
        name = existing_name
    else:
        # Minted from displayName + engine, invisible to the author (who
        # only ever sees/edits displayName) - see _engine_tag().
        name = _pascal_case(display_name) + _engine_tag(engine)

    render_fn_name = "render" + _pascal_case(name)
    component_file = "comparison" + _pascal_case(name) + ".generated.ts"

    collision = _check_chart_name_collision(name, component_file, manifest)
    if collision:
        return jsonify({"error": collision}), 400

    _atomic_write_text(
        FRONTEND_CHARTS_GENERATED_DIR / component_file,
        _generate_chart_file(render_fn_name, code, engine),
    )

    record = {
        "name": name,
        "displayName": display_name,
        "description": description,
        "code": code,
        "engine": engine,
        "exampleUsage": example_usage,
        "sampleData": sample_data,
        "componentFile": component_file,
        "componentName": render_fn_name,
        "createdAt": datetime.now(timezone.utc).isoformat(),
    }
    manifest[name] = record
    _save_chart_manifest(manifest)
    _regenerate_chart_registry(manifest)

    return jsonify({"status": "ok", **record})


def _dataflow_path(dataflow_id: str) -> Path | None:
    if not DATAFLOW_ID_RE.match(dataflow_id):
        return None
    return DATAFLOWS_DIR / f"{dataflow_id}.json"


# Durable home for a dataflow's computed outputs (e.g. A_buildings.geojson)
# - unlike data/served (OUT_DIR), which is wiped on every backend
# start/reload, this lives alongside the dataflow's own record and survives
# a restart. See _restore_computed_outputs, called at startup, which copies
# these back into OUT_DIR so a computed dataset's file is actually there
# again, not just its listing in the dataflow's projectDatasets.
def _dataflow_computed_dir(dataflow_id: str) -> Path:
    return DATAFLOWS_DIR / f"{dataflow_id}_computed"


# A view/interaction "ref" (e.g. "osm/quad_city_flooding/buildings" or
# "computed/A_buildings") names a dataset the same way /api/data-catalog and
# /api/extract-data-layer's "id" fields already do - no leading/trailing
# slash, no ".." segments (path traversal guard for the resolver below).
REF_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_\-./]*$")


def _resolve_data_source(ref: str, dataflow_id: str | None) -> tuple[Path, str] | None:
    """Maps a "ref" to the directory it should be read from (or written
    into): a "computed/" prefix scopes it to the current dataflow's own
    computed outputs (data/dataflows/{dataflow_id}_computed/, requires a
    valid dataflow_id); anything else is a path into the shared, read-only
    data catalog (data/catalog/). Returns (base_dir, rel_ref) with rel_ref
    stripped of the "computed/" prefix and still extension-less, or None if
    ref is malformed or a computed ref has no usable dataflow_id."""
    if not ref or not REF_RE.match(ref) or ".." in ref.split("/"):
        return None

    if ref.startswith("computed/"):
        if not dataflow_id or not DATAFLOW_ID_RE.match(dataflow_id):
            return None
        rel_ref = ref[len("computed/"):]
        if not rel_ref:
            return None
        return _dataflow_computed_dir(dataflow_id), rel_ref

    return CATALOG_DIR, ref


def _safe_data_path(base_dir: Path, rel_ref: str, ext: str) -> Path | None:
    """Joins rel_ref + ext onto base_dir, refusing to resolve outside it."""
    full_path = (base_dir / f"{rel_ref}.{ext}").resolve()
    try:
        full_path.relative_to(base_dir.resolve())
    except ValueError:
        return None
    return full_path


def _safe_data_dir(base_dir: Path, rel_ref: str) -> Path | None:
    """Like _safe_data_path but for a ref that names a folder (a raster
    tile set) rather than a single file."""
    full_dir = (base_dir / rel_ref).resolve()
    try:
        full_dir.relative_to(base_dir.resolve())
    except ValueError:
        return None
    return full_dir


def _restore_computed_outputs() -> None:
    for record_path in DATAFLOWS_DIR.glob("*.json"):
        try:
            record = json.loads(record_path.read_text())
        except (json.JSONDecodeError, OSError):
            continue
        dataflow_id = record.get("id")
        if not isinstance(dataflow_id, str) or not DATAFLOW_ID_RE.match(dataflow_id):
            continue
        computed_dir = _dataflow_computed_dir(dataflow_id)
        if not computed_dir.is_dir():
            continue
        for f in computed_dir.glob("*.geojson"):
            try:
                shutil.copyfile(f, vector_subdir / f.name)
            except OSError as e:
                print(f"[startup] Failed to restore computed output {f}: {e}")


def _dataflow_summary(record: dict) -> dict:
    nodes = [n for n in (record.get("nodes") or []) if isinstance(n, dict)]
    edges = [e for e in (record.get("edges") or []) if isinstance(e, dict)]
    return {
        "id": record["id"],
        "name": record.get("name") or "Untitled dataflow",
        "createdAt": record.get("createdAt"),
        "updatedAt": record.get("updatedAt"),
        "nodeCount": len(nodes),
        # Just enough per node/edge to draw a canvas-layout thumbnail on the
        # Dataflows home page (see ProjectsHomePage.tsx) without shipping
        # each node's full (potentially large) `data` payload in the list
        # response.
        "nodesPreview": [
            {
                "id": n.get("id"),
                "type": n.get("type"),
                "position": n.get("position") or {"x": 0, "y": 0},
                "width": n.get("width"),
                "height": n.get("height"),
            }
            for n in nodes
        ],
        "edgesPreview": [
            {"source": e.get("source"), "target": e.get("target")} for e in edges
        ],
    }


