@app.put("/api/dataflows/<dataflow_id>")
def save_dataflow(dataflow_id: str):
    """Autosave target - Chart Studio's publish flow has its own explicit
    save, but the canvas itself has no save button, so this is called on a
    debounce every time nodes/edges change (see frontend/src/App.tsx)."""
    path = _dataflow_path(dataflow_id)
    if path is None:
        return jsonify({"error": "Invalid dataflow id"}), 400
    if not path.exists():
        return jsonify({"error": f"No dataflow with id '{dataflow_id}'"}), 404

    payload = request.get_json(silent=True) or {}
    if not isinstance(payload.get("nodes"), list) or not isinstance(payload.get("edges"), list):
        return jsonify({"error": "'nodes' and 'edges' must be arrays"}), 400

    try:
        record = json.loads(path.read_text())
    except json.JSONDecodeError:
        record = {}

    record["id"] = dataflow_id
    record["nodes"] = payload["nodes"]
    record["edges"] = payload["edges"]
    if isinstance(payload.get("name"), str) and payload["name"].strip():
        record["name"] = payload["name"].strip()
    # Optional - omitted on a save that isn't touching the project dataset
    # list leaves whatever was already persisted untouched.
    if isinstance(payload.get("projectDatasets"), list):
        record["projectDatasets"] = payload["projectDatasets"]
    record.setdefault("projectDatasets", [])
    record.setdefault("createdAt", datetime.now(timezone.utc).isoformat())
    record["updatedAt"] = datetime.now(timezone.utc).isoformat()

    _atomic_write_text(path, json.dumps(record))
    return jsonify({"status": "ok", **_dataflow_summary(record)})


@app.patch("/api/dataflows/<dataflow_id>")
def rename_dataflow(dataflow_id: str):
    """Renames a dataflow without touching its nodes/edges - kept separate
    from save_dataflow (PUT) so the Toolbar's rename field doesn't need to
    carry the full canvas state around just to change a name."""
    path = _dataflow_path(dataflow_id)
    if path is None:
        return jsonify({"error": "Invalid dataflow id"}), 400
    if not path.exists():
        return jsonify({"error": f"No dataflow with id '{dataflow_id}'"}), 404

    payload = request.get_json(silent=True) or {}
    name = payload.get("name")
    if not isinstance(name, str) or not name.strip():
        return jsonify({"error": "'name' must be a non-empty string"}), 400

    try:
        record = json.loads(path.read_text())
    except json.JSONDecodeError:
        record = {}

    record["id"] = dataflow_id
    record["name"] = name.strip()
    record.setdefault("nodes", [])
    record.setdefault("edges", [])
    record.setdefault("createdAt", datetime.now(timezone.utc).isoformat())
    record["updatedAt"] = datetime.now(timezone.utc).isoformat()

    _atomic_write_text(path, json.dumps(record))
    return jsonify({"status": "ok", **_dataflow_summary(record)})


@app.delete("/api/dataflows/<dataflow_id>")
def delete_dataflow(dataflow_id: str):
    path = _dataflow_path(dataflow_id)
    if path is None:
        return jsonify({"error": "Invalid dataflow id"}), 400
    if not path.exists():
        return jsonify({"error": f"No dataflow with id '{dataflow_id}'"}), 404

    path.unlink()

    computed_dir = _dataflow_computed_dir(dataflow_id)
    if computed_dir.is_dir():
        shutil.rmtree(computed_dir, ignore_errors=True)

    return jsonify({"status": "ok"})


@app.delete("/api/dataflows/<dataflow_id>/computed/<path:name>")
def delete_computed_dataset(dataflow_id: str, name: str):
    """Deletes one durable computed output (e.g. "A_buildings.geojson") from
    this dataflow's data/dataflows/{dataflow_id}_computed/ dir - unlike the
    catalog (shared, read-only source data), a computed dataset is owned by
    this dataflow, so "remove from project" on one actually deletes it: a
    View/Interaction ref still pointing at "computed/{name}" will then fail
    to resolve, which is the correct signal that it's gone."""
    if not DATAFLOW_ID_RE.match(dataflow_id):
        return jsonify({"status": "error", "error": "Invalid dataflow id"}), 400

    def _resolve_within(base_dir: Path) -> Path | None:
        candidate = (base_dir / name).resolve()
        try:
            candidate.relative_to(base_dir.resolve())
        except ValueError:
            return None
        return candidate

    computed_path = _resolve_within(_dataflow_computed_dir(dataflow_id))
    if computed_path is None:
        return jsonify({"status": "error", "error": "Invalid name"}), 400

    removed = False
    if computed_path.is_file():
        computed_path.unlink()
        removed = True

    # extract-data-layer also writes a served/vector mirror alongside the
    # durable computed copy (see extract_data_layer) - remove it too, or
    # serve_vector's served-fallback would keep handing out the stale file.
    served_path = _resolve_within(vector_subdir)
    if served_path is not None and served_path.is_file():
        served_path.unlink()
        removed = True

    return jsonify({"status": "ok", "removed": removed})


@app.post("/api/infer-filetype")
def infer_filetype():
    payload = request.get_json(silent=True) or {}

    ref_keys = ["ref", "ref_base", "ref_comp"]
    ref = None

    for key in ref_keys:
        if key in payload and payload[key]:
            ref = payload[key]
            break

    if not ref:
        return jsonify({"ok": False, "error": "missing ref"}), 400
    
    result = {
        "ok": True,
        "ref": ref,
        "kind": None,       # "vector" | "raster" | None
        "is_dir": None,     # bool | None
        "file_type": None,        # ".geojson" | ".png" | etc | None
        "path": None,       # optional debug
    }

    vector_path = next(vector_subdir.glob(f"{ref}.*"), None)
    if vector_path is not None:
        return jsonify({
            "ok": True,
            "kind": "vector",
            "is_dir": False,
            "file_type": vector_path.suffix.lower(),
        }), 200
    
    # -------------------------
    # 2) Raster (file OR directory)
    # -------------------------

    # Case 1: direct file match (e.g., A.tif)
    raster_file = next(raster_subdir.glob(f"{ref}.*"), None)
    if raster_file is not None and raster_file.is_file():
        return jsonify({
            "ok": True,
            "kind": "raster",
            "is_dir": False,
            "file_type": raster_file.suffix.lower(),
        }), 200


    # Case 2: directory match (e.g., raster/A/)
    raster_path = raster_subdir / ref
    if raster_path.exists() and raster_path.is_dir():
        any_file = next((p for p in raster_path.iterdir() if p.is_file()), None)
        ext = any_file.suffix.lower() if any_file else None

        return jsonify({
            "ok": True,
            "kind": "raster",
            "is_dir": True,
            "file_type": ext,
        }), 200

    # -------------------------
    # 3) Not found
    # -------------------------
    return jsonify({
        "ok": True,
        "kind": None,
        "is_dir": None,
        "file_type": None,
    }), 200


